<?php

declare(strict_types=1);

/**
 * The PHP client's tests. No framework, no composer dependency: the library
 * has none, and a test harness that needs an install is a reason not to run
 * the tests.
 *
 * The test that matters most is the FIRST one. This is a second
 * implementation of an envelope that four JavaScript clients already build,
 * and a second implementation of a crypto format is only safe while something
 * compares the two. The vector below was produced by the Node implementation
 * with a fixed key and IV; if PHP and JavaScript ever disagree by a byte, a
 * link made in a PHP application stops opening in the browser, and the person
 * holding it sees "could not decrypt" with no idea why.
 *
 *     php tests/run.php
 */

require __DIR__ . '/../src/EasyToPasteException.php';
require __DIR__ . '/../src/Crypto.php';
require __DIR__ . '/../src/Link.php';
require __DIR__ . '/../src/Client.php';

use EasyToPaste\Client;
use EasyToPaste\Crypto;
use EasyToPaste\EasyToPasteException;
use EasyToPaste\Link;

$failures = 0;
$count = 0;

function check(string $what, callable $fn): void
{
    global $failures, $count;
    $count++;
    try {
        $fn();
        echo "ok   {$what}\n";
    } catch (Throwable $e) {
        $failures++;
        echo "FAIL {$what}\n     " . $e->getMessage() . "\n";
    }
}

function assertSame(mixed $expected, mixed $actual, string $message = ''): void
{
    if ($expected !== $actual) {
        $e = is_string($expected) ? $expected : var_export($expected, true);
        $a = is_string($actual) ? $actual : var_export($actual, true);
        throw new RuntimeException($message . "\n     expected: {$e}\n     actual:   {$a}");
    }
}

function assertTrue(bool $value, string $message = 'expected true'): void
{
    if (!$value) {
        throw new RuntimeException($message);
    }
}

// ---------------------------------------------------------------------------
// 1. The cross-language vector. Generated by the Node implementation:
//    key and iv fixed, so the whole envelope is deterministic.
// ---------------------------------------------------------------------------
$VECTOR = [
    'key' => base64_decode('MDEyMzQ1Njc4OWFiY2RlZjAxMjM0NTY3ODlhYmNkZWY=', true),
    'iv' => base64_decode('YWJjZGVmZ2hpamts', true),
    'plaintext' => "hunter2 \u{2014} a password with a dash and a unicode em dash",
    'envelope_b64url' => 'YWJjZGVmZ2hpamtsvFbq5d0_VM_dx427K8v8ogG5p8uul1_zgZxmMWu5KF4vQsxwy-RPLHfKVryzfKqLH6CAnUAw0sJqD_7JbfzjuL4w0ZTfPwWT',
];

check('PHP builds the exact envelope the JavaScript clients build', function () use ($VECTOR) {
    $envelope = Crypto::encrypt($VECTOR['plaintext'], $VECTOR['key'], $VECTOR['iv']);
    assertSame(
        $VECTOR['envelope_b64url'],
        Crypto::toBase64Url($envelope),
        'the envelope differs from the Node implementation, so a link made here will not open in a browser'
    );
});

check('PHP decrypts an envelope the JavaScript clients made', function () use ($VECTOR) {
    $envelope = Crypto::fromBase64Url($VECTOR['envelope_b64url']);
    assertSame($VECTOR['plaintext'], Crypto::decrypt($envelope, $VECTOR['key']));
});

check('the layout is [iv 12][tag 16][ciphertext]', function () use ($VECTOR) {
    $envelope = Crypto::fromBase64Url($VECTOR['envelope_b64url']);
    assertSame($VECTOR['iv'], substr($envelope, 0, 12), 'the iv is not first');
    assertSame(
        strlen($VECTOR['plaintext']) + 28,
        strlen($envelope),
        'the envelope is not iv + tag + ciphertext'
    );
});

check('a round trip works with a random key', function () {
    $key = Crypto::generateKey();
    assertSame(32, strlen($key));
    $envelope = Crypto::encrypt('correct horse battery staple', $key);
    assertSame('correct horse battery staple', Crypto::decrypt($envelope, $key));
});

check('a wrong key fails without saying why', function () {
    $envelope = Crypto::encrypt('secret', Crypto::generateKey());
    try {
        Crypto::decrypt($envelope, Crypto::generateKey());
        throw new RuntimeException('decryption with a wrong key succeeded');
    } catch (EasyToPasteException $e) {
        assertTrue(
            str_contains($e->getMessage(), 'wrong key, or the data was altered'),
            'a wrong key and a tampered ciphertext must give the same answer'
        );
    }
});

check('a tampered ciphertext is refused', function () {
    $key = Crypto::generateKey();
    $envelope = Crypto::encrypt('secret', $key);
    $tampered = substr($envelope, 0, -1) . chr(ord(substr($envelope, -1)) ^ 0x01);
    try {
        Crypto::decrypt($tampered, $key);
        throw new RuntimeException('a flipped bit decrypted anyway');
    } catch (EasyToPasteException $e) {
        // expected
    }
});

// ---------------------------------------------------------------------------
// 2. The link: the key goes after the # and nowhere else.
// ---------------------------------------------------------------------------
check('the link carries the key in the fragment', function () {
    $key = Crypto::generateKey();
    $link = Link::build('MFRGGZDFMZTWQ2LKNNWG23TP', $key);
    assertTrue(str_contains($link, '/s/MFRGGZDFMZTWQ2LKNNWG23TP#k='), "unexpected link shape: {$link}");
    $before = substr($link, 0, strpos($link, '#'));
    assertTrue(
        !str_contains($before, Crypto::toBase64Url($key)),
        'the key appears BEFORE the #, which means it would be sent to the server'
    );
});

check('a link round-trips through parse', function () {
    $key = Crypto::generateKey();
    $parsed = Link::parse(Link::build('MFRGGZDFMZTWQ2LKNNWG23TP', $key));
    assertSame('MFRGGZDFMZTWQ2LKNNWG23TP', $parsed['locator']);
    assertSame($key, $parsed['key']);
});

check('a locator that is not one is refused', function () {
    try {
        Link::build('short', Crypto::generateKey());
        throw new RuntimeException('an invalid locator was accepted');
    } catch (EasyToPasteException $e) {
        // expected
    }
});

// ---------------------------------------------------------------------------
// 3. The request body: ciphertext and metadata, and nothing else.
// ---------------------------------------------------------------------------
check('the request body carries no plaintext and no key', function () {
    $key = Crypto::generateKey();
    $envelope = Crypto::encrypt('hunter2', $key);
    $body = Client::createBody(Crypto::toBase64Url($envelope), 7, true, 3);
    $keys = array_keys($body);
    sort($keys);
    assertSame([
        'ciphertext', 'envelopeVersion', 'expiresInDays', 'mimeHint', 'mode',
        'oneTime', 'requiresRecipientLogin', 'sizeBytes', 'type',
    ], $keys, 'the request body gained or lost a field');

    $json = json_encode($body);
    assertTrue(!str_contains((string) $json, 'hunter2'), 'the plaintext reached the request body');
    assertTrue(
        !str_contains((string) $json, Crypto::toBase64Url($key)),
        'the key reached the request body'
    );
});

// ---------------------------------------------------------------------------
// 4. The channel, which is how an install from Packagist is distinguishable.
// ---------------------------------------------------------------------------
check('the User-Agent names the client and can carry its channel', function () {
    assertSame('easytopaste-php/0.1.0', Client::userAgent('0.1.0', ''));
    assertSame('easytopaste-php/0.1.0 (composer)', Client::userAgent('0.1.0', 'Composer'));
    assertSame('ab', Client::channelTag("a\r\nb"), 'a header value must not carry a newline');
    assertSame('aaaaaaaaaaaaaaaa', Client::channelTag(str_repeat('a', 40)));
});

echo "\n{$count} checks, {$failures} failed\n";
exit($failures === 0 ? 0 : 1);
