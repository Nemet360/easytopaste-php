<?php

declare(strict_types=1);

namespace EasyToPaste;

/**
 * The envelope, in PHP, byte-identical to the one the browser and the CLI build.
 *
 * Layout: [iv 12][tag 16][ciphertext N], AES-256-GCM, then base64url with the
 * padding stripped. That order is not arbitrary and it is not ours to change:
 * the browser client packs it this way, and a link made here has to open in a
 * browser, in the terminal and in an editor. PHP's openssl_encrypt hands the
 * tag back separately, which is why this file looks different from the
 * JavaScript and produces the same bytes.
 *
 * `tests/run.php` proves that against a fixed vector generated by the Node
 * implementation: same key, same IV, same bytes out. A second implementation
 * of a crypto envelope is only safe while something compares the two.
 */
final class Crypto
{
    public const KEY_BYTES = 32;
    public const IV_BYTES = 12;
    public const TAG_BYTES = 16;
    /** The API refuses an inline secret larger than this. */
    public const MAX_INLINE_BYTES = 262144;

    public static function generateKey(): string
    {
        return random_bytes(self::KEY_BYTES);
    }

    /** base64url, no padding — the form the link fragment and the API use. */
    public static function toBase64Url(string $raw): string
    {
        return rtrim(strtr(base64_encode($raw), '+/', '-_'), '=');
    }

    public static function fromBase64Url(string $value): string
    {
        $padded = strtr($value, '-_', '+/');
        $remainder = strlen($padded) % 4;
        if ($remainder !== 0) {
            $padded .= str_repeat('=', 4 - $remainder);
        }
        $raw = base64_decode($padded, true);
        if ($raw === false) {
            throw new EasyToPasteException('value is not valid base64url');
        }

        return $raw;
    }

    /**
     * @param string $plaintext UTF-8
     * @param string $key       32 raw bytes
     * @param string|null $iv   12 raw bytes; only tests pass this
     */
    public static function encrypt(string $plaintext, string $key, ?string $iv = null): string
    {
        if (strlen($key) !== self::KEY_BYTES) {
            throw new EasyToPasteException('key must be exactly 32 bytes');
        }
        $iv ??= random_bytes(self::IV_BYTES);
        if (strlen($iv) !== self::IV_BYTES) {
            throw new EasyToPasteException('iv must be exactly 12 bytes');
        }
        $tag = '';
        $ciphertext = openssl_encrypt(
            $plaintext,
            'aes-256-gcm',
            $key,
            OPENSSL_RAW_DATA,
            $iv,
            $tag,
            '',
            self::TAG_BYTES
        );
        if ($ciphertext === false) {
            throw new EasyToPasteException('encryption failed: ' . openssl_error_string());
        }

        // Tag in FRONT of the ciphertext, behind the iv. OpenSSL would append
        // it; the browser puts it here, so this does too.
        return $iv . $tag . $ciphertext;
    }

    public static function decrypt(string $envelope, string $key): string
    {
        $minimum = self::IV_BYTES + self::TAG_BYTES;
        if (strlen($envelope) < $minimum) {
            throw new EasyToPasteException(
                'envelope is too short: ' . strlen($envelope) . ' bytes, minimum ' . $minimum
            );
        }
        $iv = substr($envelope, 0, self::IV_BYTES);
        $tag = substr($envelope, self::IV_BYTES, self::TAG_BYTES);
        $ciphertext = substr($envelope, $minimum);

        $plaintext = openssl_decrypt(
            $ciphertext,
            'aes-256-gcm',
            $key,
            OPENSSL_RAW_DATA,
            $iv,
            $tag
        );
        if ($plaintext === false) {
            // Deliberately one message for every failure: a wrong key, a
            // tampered ciphertext and a truncated tag are the same answer to
            // whoever is asking, and telling them apart is a gift to an attacker.
            throw new EasyToPasteException('could not decrypt: wrong key, or the data was altered');
        }

        return $plaintext;
    }
}
